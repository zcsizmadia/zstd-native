//! x86-64 assembly for the 4-stream Huffman fast loops: a port of
//! libzstd's `huf_decompress_amd64.S` (same registers and instruction
//! sequence) to `asm!`.
//!
//! The asm only runs the inner loop until `op[3]` reaches `olimit`; the
//! caller (`huf::fast_loop_asm`) computes `olimit` from the input and output
//! room exactly like the Rust loops, so the asm never needs bounds checks.
//! Uses BMI2 (`shrx`/`shlx`): call only when the CPU has it.
//!
//! `rbx` and `rbp` can't be `asm!` operands, so the templates save and
//! restore them (and use the stack for spills, so no `nostack`).
//! The templates are generated (4-stream unrolling) and kept verbatim.
#![allow(unsafe_code)]

use core::arch::asm;

/// Loop state, laid out as libzstd's `HUF_DecompressFastArgs` prefix.
#[repr(C)]
pub(crate) struct AsmArgs {
    pub ip: [*const u8; 4],
    pub op: [*mut u8; 4],
    pub bits: [u64; 4],
    pub dt: *const u8,
    pub olimit: *mut u8,
}

